"""Regenerate source-separated Lean rule data and canonical placements from the catalog.

Run from the repository root. The catalog remains the reviewed input; existing
v1 declarations are reused, never replaced. No core semantics are generated.
"""
import collections
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[4]
CATALOG = ROOT / 'docs/rules/catalog.json'
rules = json.loads(CATALOG.read_text())
selected = [r for r in rules if r['fit'] == 'spec-data']
assert len(selected) == 124
sources = {'cms': 'Cms', 'ca-title22': 'Title22', 'ca-statutes': 'CaStatutes',
           'federal-rx': 'Federal', 'entrenched': 'Entrenched'}
base = (ROOT / 'lean/Ehr/Specs/V1.lean').read_text()
base_ids = {k: set(re.findall(r'def (\w+)\s*:\s*' + t, base))
            for k, t in [('elements', 'ElementSpec'), ('infos', 'InfoSpec'), ('commits', 'CommitSpec')]}
q = lambda s: json.dumps(s, ensure_ascii=False)
ls = lambda xs: '[' + ', '.join(xs) + ']'
roles = lambda xs: ls(['.' + s for s in xs])
when = lambda s: '.' + s if ' ' not in s else '.' + s.split(' ', 1)[0] + ' ' + q(s.split(' ', 1)[1])
source = lambda r: sources[Path(r['sourceLocations'][0]['file']).stem]

def doc(rs, text):
    labels = []
    for r in rs:
        label = ('Law: ' + r['citation']) if r['basis'] == 'law' else (
            'Entrenched: ' + r['entrenchedBecause'] + ' (' + r['citation'] + ')')
        labels.append(label + '. Catalog: ' + ', '.join(r['sourceIds']) + '.')
    return '/-- ' + '\n'.join(dict.fromkeys(labels)) + '\n' + text.replace('-/', '- /') + ' -/\n'

# An exact shared encoding has one definition, carrying all of its citations.
items = {k: collections.OrderedDict() for k in ['elements', 'infos', 'commits', 'entries', 'reviews', 'alerts']}
for r in selected:
    for k in items:
        for value in r['proposedEncoding'][k]:
            key = value['id'] if 'id' in value else json.dumps(value, sort_keys=True)
            if key not in items[k]: items[k][key] = [value, []]
            items[k][key][1].append(r)

out = {s: ['import Ehr.Core.Types\n\n/-! Source rule data generated by Rules/encode.py.\n'
           'Open narratives are nonempty codes, not validated clinical statements.\n'
           'Artifact commits capture one artifact; they do not prove event coverage. -/\n\n'
           f'namespace Ehr.Specs.Rules.{s}\n'] for s in sources.values()}
names = {s: collections.defaultdict(list) for s in out}
for k, pairs in items.items():
    for i, (value, rs) in enumerate(pairs.values()):
        s = source(rs[0])
        if k in base_ids and value['id'] in base_ids[k]: continue
        name = value.get('id', k[:-1] + str(i + 1))
        typ = {'elements': 'ElementSpec', 'infos': 'InfoSpec', 'commits': 'CommitSpec',
               'entries': 'EntryReq', 'reviews': 'ReviewReq', 'alerts': 'AlertSpec'}[k]
        if k == 'elements':
            kind = '.' + value['kind']
            if value['kind'] == 'coded': kind += ' ' + q(value['valueSet'])
            if value['kind'] == 'quantity': kind += ' .' + value['unit']
            body = f'  id := {q(value["id"])}\n  label := {q(value["label"])}\n  kind := {kind}\n' + \
                f'  enteredBy := {roles(value["enteredBy"])}\n  prefill := .{value["prefill"]}\n' + \
                f'  friction := .{value["friction"]}\n  humanOnly := {str(value["humanOnly"]).lower()}\n' + \
                f'  fhirTarget := {q(value["fhirTarget"])}'
            explanation = rs[0]['fitReason']
        elif k == 'infos':
            body = f'  id := {q(value["id"])}\n  label := {q(value["label"])}\n  version := {q(value["version"])}'
            explanation = value['label']
        elif k == 'commits':
            body = f'  id := {q(value["id"])}\n  label := {q(value["label"])}\n  roles := {roles(value["roles"])}'
            explanation = 'Dedicated artifact action. Role names do not attest licensure or physical care.'
        elif k == 'entries':
            body = f'  commit := {q(value["commit"])}\n  element := {q(value["element"])}\n  when := {when(value["when"])}\n' + \
                f'  perOrderLine := {str(value["perOrderLine"]).lower()}'
            if value['allowed'] is not None: body += '\n  allowed? := some ' + ls([q(x) for x in value['allowed']])
            explanation = rs[0]['fitReason']
        elif k == 'reviews':
            assert value['mode'] == 'shownOnCommit' and value['waivedBy'] is None
            body = f'  commit := {q(value["commit"])}\n  info := {q(value["info"])}\n  mode := .shownOnCommit\n  when := {when(value["when"])}'
            explanation = 'Pin live artifact content during the human commit; no receipt or waiver substitutes.'
        else: raise AssertionError('No new alerts are proposed')
        out[s].append('\n' + doc(rs, explanation) + f'def {name} : {typ} where\n{body}\n')
        names[s][k].append(name)
for s, chunks in out.items():
    for k in items:
        typ = {'elements': 'ElementSpec', 'infos': 'InfoSpec', 'commits': 'CommitSpec',
               'entries': 'EntryReq', 'reviews': 'ReviewReq', 'alerts': 'AlertSpec'}[k]
        chunks.append(f'\n/-- Product design property. {s} contributions, with source labels on each item. -/\ndef {k} : List {typ} :=\n  ' + ls(names[s][k]) + '\n')
    chunks.append(f'\nend Ehr.Specs.Rules.{s}\n')
    (ROOT / f'lean/Ehr/Specs/Rules/{s}.lean').write_text(''.join(chunks))

# Canonical placement data. Group by artifact/commit, suppress repeated fields
# on the same screen at runtime, and retain every existing component and route.
placements = collections.defaultdict(lambda: {'entries': [], 'reviews': [], 'commits': [], 'workflow': ''})
routes = collections.defaultdict(set)
for r in selected:
    p = r['proposedEncoding']
    for place in p['placement']:
        dest = placements[place['screen']]
        dest['workflow'] = place['workflow']
        for k in ('entries', 'reviews', 'commits'):
            for x in p[k]:
                # This catalog row bundles the prescription and refill decisions;
                # its composer placements are not refill-decision screens.
                if r['id'] == 'federal-rx-1306-12-zero-refills':
                    commit = x.get('commit', x.get('id'))
                    if (commit == 'signOrders') == (place['screen'] == 'w7Decision'):
                        continue
                if x not in dest[k]: dest[k].append(x)
    for route in p['workflowRoutes']: routes[route['fromWorkflow']].add(route['screen'])
parts = ['import Ehr.Canonical.Builders\nimport Ehr.Specs.V1\n\nnamespace Ehr.Canonical.Rules\n\n',
         '/-- Reviewed screen placements: screen, workflow, element, per-line, section. -/\n',
         'def fields : List (ScreenId × String × ElementId × Bool × String) :=\n  [']
rows = []
for screen, p in placements.items():
    for e in p['entries']:
        rows.append(f'({q(screen)}, {q(p["workflow"])}, {q(e["element"])}, {str(e["perOrderLine"]).lower()}, {q(e["commit"])})')
parts.append(',\n   '.join(dict.fromkeys(rows)) + ']\n')
parts += ['\n/-- Panels required beside each artifact action, outside closed groups/tabs. -/\n',
          'def panels : List (ScreenId × InfoId) :=\n  ' + ls(list(dict.fromkeys(
              f'({q(s)}, {q(r["info"])})' for s, p in placements.items() for r in p['reviews']))) + '\n',
          '\n/-- Artifact actions on the reviewed screens. Existing actions are preserved. -/\n',
          'def actions : List (ScreenId × String × CommitId) :=\n  ' + ls(list(dict.fromkeys(
              f'({q(s)}, {q(p["workflow"])}, {q(c["id"])})' for s, p in placements.items() for c in p['commits'] if c['id'] != 'signOrders' or s.endswith('Sign')))) + '\n',
          '\n/-- Explicit shared-service navigation, preserving Back history. -/\n',
          'def routes : List (String × ScreenId) :=\n  ' + ls([
              f'({q(w)}, {q(s)})' for w, screens in routes.items() for s in sorted(screens)]) + '\n']
(ROOT / 'lean/Ehr/Canonical/RulePlacements.lean').write_text(''.join(parts) + '\nend Ehr.Canonical.Rules\n')

# Catalog audit: no row is silently dropped. Existing rows link to their
# audited existing spec items; non-data rows retain the classification reason.
for r in rules:
    if r['fit'] == 'spec-data':
        p = r['proposedEncoding']
        r['encodedIn'] = sorted(set(
            [k[:-1] + ':' + v['id'] for k in ('elements', 'infos', 'commits') for v in p[k]] +
            ['entry:' + e['commit'] + ':' + e['element'] + ':' + e['when'] for e in p['entries']] +
            ['review:' + e['commit'] + ':' + e['info'] + ':' + e['when'] for e in p['reviews']]))
        r.pop('encodingSkippedReason', None)
        r['encodingNote'] = 'Spec v1 data; v1.1/v2 inherit. Scope and backend limits in encoding-plan.md apply.'
        if r['id'] == 'ca-statutes-bpc-741-education-exceptions':
            r['encodingNote'] += ' The existing naloxoneEducation flag remains required as stricter hospital policy; the outcome enum does not replace it.'
        if p['infos']:
            r['encodingNote'] += ' Panel identifiers/guards are encoded; actual renderer payload bindings remain CR-15 work.'
        if any(e['when'] in ('orderClass controlled-V', 'drugClass ghb') for e in p['entries']):
            r['encodingNote'] += ' Controlled-V/GHB branches require actual formulary support from core/world; no demo products currently carry these tags.'

    elif r['fit'] == 'existing':
        r['encodedIn'] = r.get('existingSpecItems', [])
        r.pop('encodingSkippedReason', None)
    else:
        r['encodedIn'] = []
        r['encodingSkippedReason'] = r['fit'] + ': ' + r['fitReason']
CATALOG.write_text(json.dumps(rules, indent=2, ensure_ascii=False) + '\n')
print(f'Generated {len(selected)} rule encodings in five source modules and canonical placements.')

