"""Generate additive feature rule ASTs, placements, and catalog provenance."""
import collections
import json
from pathlib import Path
import re
from human_labels import label as human_label
from feature_data import TEMP, PAT, VAL, EXP, DISPLAY, SKIP, q
ROOT=Path(__file__).resolve().parents[4]
rs=json.loads((ROOT/'docs/rules/catalog.json').read_text()); byid={r['id']:r for r in rs}
fits={'core-feature:'+s for s in ['event-time-window','patient-predicate','value-validation','order-expiry-clock','structured-display']}
selected=[r for r in rs if r['fit'] in fits]
assert len(selected)==181
assert {x['id'] for xs in [TEMP,PAT,VAL,EXP,DISPLAY] for x in xs}|SKIP.keys()=={r['id'] for r in selected}
ls=lambda xs:'['+', '.join(xs)+']'
opt=lambda x:'none' if x is None else 'some ('+x+')'
boolstr=lambda b:str(b).lower()
source=(ROOT/'lean/Ehr/Specs/V1.lean').read_text()
# New generator runs may see its own exported additions: source definitions remain authoritative.
base_elements=set(re.findall(r'def (\w+)\s*:\s*ElementSpec',source))|{e['id'] for r in rs if r['fit']=='spec-data' for e in r['proposedEncoding']['elements']}
base_commits=set(re.findall(r'def (\w+)\s*:\s*CommitSpec',source))|{c['id'] for r in rs if r['fit']=='spec-data' for c in r['proposedEncoding']['commits']}
chunks=['import Ehr.Core.Types\n\n/-! Generated by feature_encode.py from reviewed feature_data.py.\nTrusted record evidence is never created by an input or checkbox. Unknown applicability fails closed.\nEvery original requirement is retained. Scope/adapter gaps are recorded per catalog row. -/\nnamespace Ehr.Specs.Rules.Features\n']
manifest=collections.defaultdict(list); objs=collections.defaultdict(list)
def emit(id,name,typ,body,note=''):
 r=byid[id]
 label='Law: '+r['citation'] if r['basis']=='law' else 'Entrenched: '+r['entrenchedBecause']+' ('+r['citation']+')'
 chunks.append('\n/-- '+label+'. Catalog: '+', '.join(r['sourceIds'])+'.\n'+r['proposedRule'].replace('-/','- /')+'\n'+note.replace('-/','- /')+' -/\n'+f'def {name} : {typ} :=\n  '+body+'\n')
 manifest[id].append(name)
 objs[id].append(dict(name=name,type=typ))
 if typ == 'EntryReq':
  for field in ('commit','element'):
   match=re.search(field+r' := (\"(?:[^\"\\]|\\.)*\")',body)
   assert match, (name, field)
   objs[id][-1][field]=json.loads(match[1])
# Explicit event and expiry ids survive Lean JSON export for audit.
for n,t in enumerate(TEMP):
 name=f'temporal{n+1:03d}';t['name']=name
 # Sterilization consent is actual evidence; only the future procedure anchor can be planned.
 if t['commit']=='authorizeSterilization':
  t={**t,'subject':'sterilization.consent','anchor':'sterilization.procedure','lo':-t['hi'],'hi':-t['lo'],'deadline':-t['lo']}
 body='{ id := '+q(t['id']+':'+name)+', subject := { event := '+q(t['subject'])+', artifactKey := '+q(t['key'])+' }, anchor := { event := '+q(t['anchor'])+', artifactKey := '+q(t['key'])+' }, minOffset := '+str(t['lo'])+', maxOffset := '+str(t['hi'])+', deadline := '+str(t['deadline'])+', metric := '+t['metric']+', when? := '+opt(t['when'])+', direction? := '+opt(t['direction'])+' }'
 emit(t['id'],name,'TemporalReq',body,t['note'])
 objs[t['id']][-1].update(commit=t['commit'],id=t['id']+':'+name)
for n,e in enumerate(EXP):
 name=f'expiry{n+1:03d}';e['name']=name
 policy=lambda p:opt(None if p is None else '{ event := '+q(p[0])+', validForMinutes := '+str(p[1])+' }')
 body='{ id := '+q(e['id'])+', orderKey := '+q(e['key'])+', anchor := .'+e['anchor']+', duration := '+e['duration']+', when? := '+opt(e['when'])+', renewal? := '+policy(e['renew'])+', reassessment? := '+policy(e['reassess'])+', maxOriginalMinutes? := '+opt(None if e['maximum'] is None else str(e['maximum']))+' }'
 emit(e['id'],name,'ExpiryReq',body,'Original issue/start/first-fill anchors survive episodes/transfers. Backend release/auto-stop and practitioner qualification remain trusted adapter/authorization duties.')
 objs[e['id']][-1].update(commit=e['commit'],id=e['id'])
# Elements and entries: preserve existing declarations; append validators by conjunction.
elements={}; entries=[]; alerts=[]; validations=[]
def add_element(id,e,label,kind,sample,validation='.nonempty',default=None,target='Observation.valueString'):
 if e not in base_elements and e not in elements:
  name='element'+e[0].upper()+e[1:]
  body='{ id := '+q(e)+', label := '+q(human_label(e,label))+', kind := '+kind+', enteredBy := [.physician, .np, .rn, .surgeon], prefill := '+('.defaultConfirm' if default else '.never')+', humanOnly := '+boolstr(not default)+', friction := .compliance, fhirTarget := '+q(target)+', validation? := some ('+validation+'), defaultValue? := '+opt(q(default) if default else None)+' }'
  emit(id,name,'ElementSpec',body,'Synthetic samples are test data, never clinician defaults (except the mandated weekly methotrexate default).')
  elements[e]=(name,sample)
for n,p in enumerate(PAT):
 if 'alert' in p:
  name='clinicalAlert'+str(n)
  emit(p['id'],name,'AlertSpec','{ id := '+q(p['alert'])+', label := '+q(byid[p['id']]['title'])+', cond := .clinical ('+p['when']+'), tier := .interruptive, commit := '+q(p['commit'])+' }','Threshold calculations are trusted current-version risk observations, not inferred by the UI.')
  alerts.append(name);continue
 e=p['element']; validation='.nonempty' if p['kind'] in ['.text'] or p['kind'].startswith('.coded') else '.quantityRange .none 0 1000000' if p['kind'].startswith('.quantity') else None
 add_element(p['id'],e,p['label'],p['kind'],p['sample'],validation or '.nonempty',target=p['target'])
 # Flags do not accept nonempty validation (text-only); omit it for flags.
 if p['kind']=='.flag' and e in elements:
  chunks[-1]=chunks[-1].replace('validation? := some (.nonempty), ','')
 def entry(when,allowed,suffix):
  name=f'predicateEntry{n+1:03d}'+suffix
  body='{ commit := '+q(p['commit'])+', element := '+q(e)+', when := '+('.always' if when is None else '.clinical ('+when+')')+', allowed? := '+opt(None if allowed is None else ls([q(s) for s in allowed]))+' }'
  emit(p['id'],name,'EntryReq',body,'Eligibility failures cannot be attested away: the invalid branch has an empty allowed set. Use the separate refused-treatment decision for non-treatment.')
  entries.append(name);objs[p['id']][-1].update(commit=p['commit'],element=e)
 if p.get('legal'):
  entry(None,None,'Human');entry('.not ('+p['legal']+')',[],'Eligibility')
 else:entry(p['when'],p['allowed'],'')
for n,v in enumerate(VAL):
 e=v['element']
 targets={'preferredLanguage':'Patient.communication.language','birthDate':'Patient.birthDate','directSupplyDays':'MedicationDispense.daysSupply',
          'oralLiquidDose':'MedicationRequest.dosageInstruction.doseAndRate.doseQuantity','prescribedAmountText':'MedicationRequest.dosageInstruction.text',
          'oralMethotrexateFrequency':'MedicationRequest.dosageInstruction.timing.code','calculatedPediatricDose':'MedicationRequest.dosageInstruction.doseAndRate.doseQuantity'}
 add_element(v['id'],e,v['label'],v['kind'],v['sample'],v['expr'],v['default'],target=targets.get(e,'Observation.valueString'))
 name=f'validation{n+1:03d}'
 emit(v['id'],name,'Validation',v['expr'],v['note'])
 validations.append((e,name,v['default']))
 objs[v['id']][-1].update(element=e)
 if v['commit']:
  name=f'validationEntry{n+1:03d}'
  emit(v['id'],name,'EntryReq','{ commit := '+q(v['commit'])+', element := '+q(e)+', when := '+('.always' if v['when'] is None else '.clinical ('+v['when']+')')+' }',v['note'])
  entries.append(name);objs[v['id']][-1].update(commit=v['commit'],element=e)
# Arithmetic inputs have explicit units and positive denominators.
for v in VAL:
 if 'supplyDaysCeil' in v['expr']:
  for e,label,sample in [('dispenseQuantity','Quantity dispensed','3'),('dispenseDose','Units per dose','1')]:
   add_element(v['id'],e,label,'.quantity .none',sample,'.quantityRange .none 10 100000')
   name='supplyInput'+str(len(entries)); emit(v['id'],name,'EntryReq','{ commit := '+q(v['commit'])+', element := '+q(e)+' }');entries.append(name)
  add_element(v['id'],'dispenseFrequency','Dosing frequency','.coded "frequency"','daily','.codeMember "dispense-frequency" "2026-10"')
  name='frequencyInput'+str(len(entries));emit(v['id'],name,'EntryReq','{ commit := '+q(v['commit'])+', element := "dispenseFrequency" }');entries.append(name)
 if 'formulationUnit' in v['expr']:
  add_element(v['id'],'liquidFormulation','Liquid formulation','.coded "formulation"','oral-liquid','.codeMember "formulation" "2026-10"')
  name='formulationEntry';emit(v['id'],name,'EntryReq','{ commit := '+q(v['commit'])+', element := "liquidFormulation", allowed? := some ["oral-liquid"] }');entries.append(name)
 if 'doseByWeight' in v['expr']:
  name='pediatricWeightEntry';emit(v['id'],name,'EntryReq','{ commit := '+q(v['commit'])+', element := "weight" }');entries.append(name)
# Contracts merge repeated sources by conjunction/union, never by overwrite.
infos={};displays=[]
for n,d in enumerate(DISPLAY):
 if 'actionLabel' in d:
  emit(d['id'],'prescriptionSigningLabel','String',q(d['actionLabel']),'Exact semantic signing label; authentication and signing credentials remain external.')
  continue
 info=infos.setdefault(d['info'],dict(fields=[],ids=[],rows=[],group=None,label=d['label']))
 for field in d['fields']:
  f,avail=(field if isinstance(field,tuple) else (field,False))
  value='{ field := '+q(f)+', ifAvailable := '+boolstr(avail)+' }'
  if value not in info['fields']:info['fields'].append(value)
 for k,key in [('identifiers','ids'),('rows','rows')]:
  for x in d[k]:
   if x not in info[key]:info[key].append(x)
 if d['group']:info['group']=d['group']
 name=f'display{n+1:03d}'
 body='{ info := '+q(d['info'])+', scope := '+d['scope']+', pinned := true, selectionElement? := '+opt(None if d['selection'] is None else q(d['selection']))+' }'
 emit(d['id'],name,'DisplayReq',body,'Pinned, top-level, legible live payload. No receipt/waiver substitutes. Available photos may be omitted only on explicit false availability.')
 displays.append(name);objs[d['id']][-1].update(info=d['info'])
for e,label,sample in [('patientSelected','Selected patient','.true')]:
 # Selection is a UI flag; not an entry requirement for an unrelated commit.
 add_element('entrenched-safer-patient-list-selection',e,label,'.flag','true')
 chunks[-1]=chunks[-1].replace('validation? := some (.nonempty), ','')
for i,(id,info) in enumerate(infos.items()):
 d=next(d for d in DISPLAY if d.get('info')==id)
 name='payloadInfo'+str(i+1);info['name']=name
 emit(d['id'],name,'InfoSpec','{ id := '+q(id)+', label := '+q(human_label(id,info['label']))+', version := "", payload? := some { fields := '+ls(info['fields'])+', identifiers := '+ls(['.'+x for x in info['ids']])+', rowFields := '+ls([q(x) for x in info['rows']])+', groupBy? := '+opt(None if info['group'] is None else q(info['group']))+' } }')
# New actions each retain an explicit human documentation completion, identity,
# plus patient/allergy review. They are separate artifacts, not original-entry bypasses.
all_commits=sorted({x['commit'] for xs in [TEMP,PAT,VAL,EXP] for x in xs if x.get('commit')})
new=[c for c in all_commits if c not in base_commits]
owner=lambda c:next(x['id'] for xs in [TEMP,PAT,VAL,EXP] for x in xs if x.get('commit')==c)
labels={c:re.sub(r'([a-z])([A-Z])',r'\1 \2',c).capitalize() for c in new}
for c in new:
 name='commit'+c[0].upper()+c[1:]
 roles='[.physician, .np, .surgeon]' if c.startswith(('authorize','sign','continue','dispense','partialFill','completeSchedule','completeEmergency')) else '[.physician, .np, .rn, .surgeon]'
 emit(owner(c),name,'CommitSpec','{ id := '+q(c)+', label := '+q(human_label(c,labels[c]))+', roles := '+roles+' }','Roles allow documentation only; this is not qualified-authorization or a license certificate.')
 chunks.append('')
for key,typ,values in [('elements','ElementSpec',[v[0] for v in elements.values()]),('infos','InfoSpec',[i['name'] for i in infos.values()]),('commits','CommitSpec',['commit'+c[0].upper()+c[1:] for c in new]),('entries','EntryReq',entries),('alerts','AlertSpec',alerts),('displays','DisplayReq',displays)]:
 chunks.append(f'\n/-- Product design property. Additive feature {key}. -/\ndef {key} : List {typ} :=\n  '+ls(values)+'\n')
chunks.append('\n/-- Product design property. Dedicated documentation actions keep human identity. -/\ndef newCommitIds : List CommitId := '+ls([q(c) for c in new])+'\n')
chunks.append('\n/-- Product design property. Event windows by commit. -/\ndef temporalFor (key : CommitId) : List TemporalReq :=\n  '+ls(['('+q(t['commit'])+', '+t['name']+')' for t in TEMP])+'.filterMap (fun (c, r) => if c == key then some r else none)\n')
chunks.append('\n/-- Product design property. Durable clocks by commit. -/\ndef expiryFor (key : CommitId) : List ExpiryReq :=\n  '+ls(['('+q(e['commit'])+', '+e['name']+')' for e in EXP])+'.filterMap (fun (c, r) => if c == key then some r else none)\n')
chunks.append('\n/-- Product design property. Strengthening preserves existing obligations. -/\ndef strengthenCommit (c : CommitSpec) : CommitSpec :=\n  { c with\n    temporal? := some (c.temporal?.getD [] ++ temporalFor c.id ++\n      (if ["signScheduleIISeries", "signEmergencyRxFollowup", "authorizeDirectDispensing", "authorizeSelfAdministration", "authorizeBedsideMedication", "authorizePatientOwnedMedication", "authorizeOudDirectDispensing", "signOralLiquidPrescription", "signFormattedPrescription", "signOralMethotrexate"].contains c.id then temporalFor "signOrders" else []))\n    expiry? := some (c.expiry?.getD [] ++ expiryFor c.id)\n    actionLabel? := if ["signOrders", "signScheduleIISeries", "signEmergencyRxFollowup", "signOralLiquidPrescription", "signFormattedPrescription", "signOralMethotrexate"].contains c.id then some prescriptionSigningLabel else c.actionLabel? }\n')
chunks.append('\n/-- Product design property. Validation is conjoined with any existing contract. -/\ndef strengthenElement (e : ElementSpec) : ElementSpec :=\n  '+ls(['('+q(e)+', '+name+')' for e,name,_ in validations])+'.foldl (fun el (key, v) =>\n    if el.id == key then { el with validation? := some (el.validation?.map (fun old => Validation.and old v) |>.getD v) } else el) e\n')
chunks.append('\nend Ehr.Specs.Rules.Features\n')
(ROOT/'lean/Ehr/Specs/Rules/Features.lean').write_text(''.join(chunks))
# Placement manifest is deterministic. Existing commits are augmented on their
# actual screens; new related artifacts are linked from their source workflow.
workflow={c:byid[owner(c)]['workflows'][0] for c in new}
place=['import Ehr.Core.Types\nnamespace Ehr.Canonical.Features\n', '/-- Product design property. Dedicated artifact screens, by owning workflow. -/\ndef artifacts : List (ScreenId × String × CommitId) :=\n  '+ls(['('+q('feature.'+c)+', '+q(workflow[c])+', '+q(c)+')' for c in new])+'\n', '/-- Product design property. All phase contracts stay pinned across navigation. -/\ndef phaseInfos : List InfoId := '+ls([q(d['info']) for d in DISPLAY if 'scope' in d and '.phase' in d['scope'] and d['info'] not in []])+' |>.eraseDups\n', '/-- Explicit synthetic entry examples, never release prefills. -/\ndef samples : List (ElementId × String) := '+ls(['('+q(e)+', '+q(sample)+')' for e,(_,sample) in elements.items()])+'\n', '\nend Ehr.Canonical.Features\n']
route_pairs=sorted({(w,'feature.'+x['commit']) for xs in [TEMP,PAT,VAL,EXP] for x in xs if x.get('commit') in new for w in byid[x['id']]['workflows']})
place.insert(-1,'\n/-- Source workflow routes preserve shared-service context and Back history. -/\ndef routes : List (String × ScreenId) := '+ls(['('+q(w)+', '+q(screen)+')' for w,screen in route_pairs])+'\n')
(ROOT/'lean/Ehr/Canonical/FeaturePlacements.lean').write_text(''.join(place))
for r in selected:
 if r['id'] in SKIP:
  r['encodedIn']=[];r['encodingSkippedReason']=SKIP[r['id']];r.pop('featureEncoding',None);r.pop('encodingNote',None)
 else:
  r['encodedIn']=['Features.'+s for s in manifest[r['id']]];r['featureEncoding']=objs[r['id']];r.pop('encodingSkippedReason',None)
  notes=sorted({x.get('note','') for xs in [TEMP,PAT,VAL,EXP,DISPLAY] for x in xs if x['id']==r['id']} - {''})
  r['encodingNote']='Spec v1 closed AST; v1.1/v2 inherit. Trusted current-version record adapters, physical care, credentials and persistence remain owning-lane work. '+ ' '.join(notes)
(ROOT/'docs/rules/catalog.json').write_text(json.dumps(rs,indent=2,ensure_ascii=False)+'\n')
print(f'Feature pass: {len(selected)-len(SKIP)} encoded, {len(SKIP)} precise remaining language gaps; {len(TEMP)} time windows, {len(EXP)} clocks.')

