import { RELEASE_IDS } from '../src/release-config.js';
import { writeFile, readFile } from 'node:fs/promises';
import path from 'node:path';
import { fakeCanonical } from '../src/fake/fixtures.js';
import { bindBuild } from '../src/build-binding.js';
import { RunStore } from '../src/store.js';
import { tmp } from './helpers.js';
import { expandProgram } from '../src/composites.js';
const SOURCE = `import { Paper } from '@mantine/core'; import { UiNodeView, type PresentationProps } from '@ehr/presentation'; export default function Review({node,onEvent}:PresentationProps){return <Paper p="xs"><UiNodeView node={node} onEvent={onEvent}/></Paper>;}`;
it('stages program, source and component bundle together; failed bundle publication keeps the old pointer', async () => {
  const directory = await tmp('presentation-publication');
  const customRoot = path.join(directory, 'custom');
  const store = new RunStore(directory, customRoot);
  const current = fakeCanonical(RELEASE_IDS.base);
  const certificate = { specVersion: RELEASE_IDS.base, specHash: 's', programHash: 'p', verdict: 'ok' as const, checkerVersion: 'stub', time: 'now' };
  const build = { ehrSha256: '0'.repeat(64), appSha256: 'a'.repeat(64), wasmSha256: 'b'.repeat(64), componentsSha256: '0'.repeat(64) };
  await store.deploy('P1', current, certificate, bindBuild(build, current, certificate));
  const pointerFile = path.join(directory, 'programs/P1/deployed.json');
  const previous = await readFile(pointerFile, 'utf8');
  const next = { ...current, version: 1, presentationComponents: [{ name: 'Review', key: 'info', source: SOURCE }] };
  await writeFile(customRoot, 'deliberately blocks directory creation');
  await expect(store.deploy('P1', next, certificate, bindBuild(build, next, certificate))).rejects.toThrow();
  expect(await readFile(pointerFile, 'utf8')).toBe(previous);
  const validRoot = path.join(directory, 'valid-custom');
  const publishing = new RunStore(directory, validRoot);
  const pointer = await publishing.deploy('P1', next, certificate, bindBuild(build, next, certificate));
  expect(pointer.components).toBe('programs/P1/v1.components.json');
  expect(JSON.parse(await readFile(publishing.programPath('P1', 1), 'utf8'))).toEqual(expandProgram(next));
  expect((await publishing.login('P1')).program.presentationComponents).toHaveLength(1);
  expect(await publishing.deploy('P1', next, certificate, bindBuild(build, next, certificate))).toEqual(pointer);
  const changed={...next,id:'changed'};
  await expect(publishing.deploy('P1', changed, certificate, bindBuild(build, changed, certificate))).rejects.toThrow('immutable');
  await writeFile(path.join(directory, pointer.components ?? ''), '{}');
  await expect(publishing.login('P1')).rejects.toThrow();
});
