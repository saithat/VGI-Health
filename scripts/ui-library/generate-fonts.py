"""Generate integer advance tables from the repository's pinned font bytes.
Run with fonttools==4.68.0, brotli==1.2.0 (or 1.2.1). No network fonts.
"""
from pathlib import Path
import hashlib
import json
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / 'app/src/ehr/ui/fonts'
entries = []
lean = ['-- Generated by scripts/ui-library/generate-fonts.py; do not edit.',
        'import Lean', 'namespace Ehr.Layout.Fonts']
for name, weights in [('noto-sans', [400, 600, 650, 700, 750, 800]),
                      ('noto-sans-mono', [400]), ('noto-symbols', [400])]:
    path = FONTS / f'{name}.woff2'
    source = TTFont(path)
    for weight in weights:
        font = instantiateVariableFont(source, {'wght': weight}, inplace=False) if 'fvar' in source else source
        cmap = font.getBestCmap()
        upem = font['head'].unitsPerEm
        pairs = sorted((cp, font['hmtx'][glyph][0]) for cp, glyph in cmap.items())
        ident = name.replace('-', '_') + '_' + str(weight)
        lean.append(f'def {ident} : Array (Nat × Nat) := #[' + ','.join(f'({c},{w})' for c, w in pairs) + ']')
        entries.append(dict(id=ident, family=name, weight=weight, unitsPerEm=upem,
                            maxAdvance=max(w for _, w in pairs), ascent=font['hhea'].ascent, descent=-font['hhea'].descent, sha256=hashlib.sha256(path.read_bytes()).hexdigest(), glyphs=len(pairs)))
lean += ['def lineExtent : Array Nat := #[' + ','.join(str(e['ascent']+e['descent']) for e in entries) + ']',
         'def tables : Array (Array (Nat × Nat)) := #[' + ','.join(e['id'] for e in entries) + ']',
         'def unitsPerEm : Array Nat := #[' + ','.join(str(e['unitsPerEm']) for e in entries) + ']',
         'def maxAdvance : Array Nat := #[' + ','.join(str(e['maxAdvance']) for e in entries) + ']',
         'end Ehr.Layout.Fonts']
(ROOT / 'lean/Ehr/Layout/Fonts.lean').write_text('\n'.join(lean) + '\n')
(ROOT / 'scripts/ui-library/fonts.json').write_text(json.dumps(entries, indent=2) + '\n')
