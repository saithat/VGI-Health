"""Generate sorted integer advance tables from pinned WOFF2 bytes.
Run with fonttools==4.68.0 and brotli==1.2.1; no network fonts.
The six sans instances include the research CJK/Hebrew fallback repertoire.
"""
from pathlib import Path
import hashlib, json
from fontTools.ttLib import TTFont
ROOT=Path(__file__).resolve().parents[2]
LEGACY=ROOT/'app/src/ehr/ui/fonts'
WORLD=ROOT/'app/src/browser/ui-library/fonts'
manifest=json.loads((WORLD/'sources.json').read_text())
for source in manifest['sources']:
 path=WORLD/(source['name']+'.woff2')
 assert hashlib.sha256(path.read_bytes()).hexdigest()==source['sha256'], path
entries=[]
lean=['-- Generated by scripts/ui-library/generate-fonts.py; do not edit.', 'import Lean','set_option maxRecDepth 100000','set_option maxHeartbeats 4000000','namespace Ehr.Layout.Fonts']
fallbacks=[TTFont(WORLD/(name+'.woff2')) for name in ['noto-cjk','noto-hebrew']]
for name,weights,folder in [('noto-world-sans',[400,600,650,700,750,800],WORLD),('noto-sans-mono',[400],LEGACY),('noto-symbols',[400],LEGACY)]:
 for weight in weights:
  path=folder/(name+(f'-{weight}' if folder==WORLD else '')+'.woff2'); source=TTFont(path)
  font=source
  # All sources use 1000 units/em. First font wins, matching CSS fallback.
  sources=[font]
  assert all(f['head'].unitsPerEm==1000 for f in sources)
  pairs={}
  for f in sources:
   for cp,glyph in f.getBestCmap().items(): pairs.setdefault(cp,f['hmtx'][glyph][0])
  pairs=sorted(pairs.items())
  extents=sources+(fallbacks if folder==WORLD else [])
  ident=name.replace('-','_')+'_'+str(weight)
  lean.append(f'def {ident} : Array (Nat × Nat) := #['+','.join(f'({c},{w})' for c,w in pairs)+']')
  entries.append(dict(id=ident,family=name,weight=weight,unitsPerEm=1000,maxAdvance=max(f['hmtx'][g][0] for f in extents for g in f.getBestCmap().values()),ascent=max(f['hhea'].ascent for f in extents),descent=max(-f['hhea'].descent for f in extents),sha256=hashlib.sha256(path.read_bytes()).hexdigest(),glyphs=len(pairs)))
fallback_pairs={}
for font in fallbacks:
 for cp,g in font.getBestCmap().items(): fallback_pairs.setdefault(cp,font['hmtx'][g][0])
ranges=[]
for cp,width in sorted(fallback_pairs.items()):
 if ranges and cp==ranges[-1][1]+1 and width==ranges[-1][2]: ranges[-1][1]=cp
 else: ranges.append([cp,cp,width])
lean.append('def fallbackRanges : Array (Nat × Nat × Nat) := #['+','.join(f'({a},{b},{w})' for a,b,w in ranges)+']')
lean+=['def lineExtent : Array Nat := #['+','.join(str(e['ascent']+e['descent']) for e in entries)+']',
'def tables : Array (Array (Nat × Nat)) := #['+','.join(e['id'] for e in entries)+']',
'def unitsPerEm : Array Nat := #['+','.join(str(e['unitsPerEm']) for e in entries)+']',
'def maxAdvance : Array Nat := #['+','.join(str(e['maxAdvance']) for e in entries)+']','end Ehr.Layout.Fonts']
(ROOT/'lean/Ehr/Layout/Fonts.lean').write_text('\n'.join(lean)+'\n')
(ROOT/'scripts/ui-library/fonts.json').write_text(json.dumps(entries,indent=2)+'\n')
