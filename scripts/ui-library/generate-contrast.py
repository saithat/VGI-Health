"""Outward rounded sRGB bounds; exact integer certificates are checked in Lean."""
from decimal import Decimal, localcontext, ROUND_FLOOR
from pathlib import Path
with localcontext() as ctx:
    ctx.prec = 100
    rows = []
    for c in range(256):
        x = Decimal(c)/255
        y = x/Decimal('12.92') if x <= Decimal('0.04045') else ((x+Decimal('.055'))/Decimal('1.055'))**Decimal('2.4')
        lo = int((y*1000000).to_integral_value(rounding=ROUND_FLOOR))
        rows.append((lo, min(1000000,lo+1)))
p = Path(__file__).resolve().parents[2] / 'lean/Ehr/Layout/Contrast.lean'
p.write_text('''-- Generated by scripts/ui-library/generate-contrast.py.
import Ehr.Layout.Types
namespace Ehr.Layout
/-- Each channel encloses the exact IEC sRGB value in millionths. -/
def srgbBounds : Array (Nat × Nat) := #[
''' + ','.join(f'({a},{b})' for a,b in rows) + ''']
/-- Exact polynomial certificate for the nonlinear fifth root: v^5=x^12.
For c≤10 the linear branch is c/3294.6. No Float or numerical axiom. -/
def channelCertificate (c : Nat) : Bool :=
  let (lo,hi) := srgbBounds[c]!
  if c ≤ 10 then
    decide (lo * 32946 ≤ c * 10000000 ∧ c * 10000000 ≤ hi * 32946)
  else
    let a := 200*c+2805
    let b := 53805
    decide (lo^5 * b^12 ≤ a^12 * 1000000^5 ∧ a^12 * 1000000^5 ≤ hi^5 * b^12)
set_option maxRecDepth 4096 in
set_option maxHeartbeats 4000000 in
theorem channel_certificates : (List.range 256).all channelCertificate = true := by decide

def luminance (c : Color) : Nat × Nat :=
  let r := srgbBounds[c.r]?.getD (0,1000000)
  let g := srgbBounds[c.g]?.getD (0,1000000)
  let b := srgbBounds[c.b]?.getD (0,1000000)
  ((2126*r.1+7152*g.1+722*b.1)/10000,
   (2126*r.2+7152*g.2+722*b.2+9999)/10000)

def colorValid (c : Color) : Bool := c.r ≤ 255 && c.g ≤ 255 && c.b ≤ 255
/-- Conservative lower contrast, represented as numerator/denominator.
The two directions allow arbitrary author colors, rather than palette pairs. -/
def contrastBound (a b : Color) : Nat × Nat :=
  let x := luminance a
  let y := luminance b
  if x.1 ≥ y.1 then (x.1+50000,y.2+50000) else (y.1+50000,x.2+50000)

def contrastPass (a b : Color) (twiceRatio : Nat) : Bool :=
  let (n,d) := contrastBound a b
  colorValid a && colorValid b && 2*n ≥ twiceRatio*d

#print axioms channel_certificates
end Ehr.Layout
''')
