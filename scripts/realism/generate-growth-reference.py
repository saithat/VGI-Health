#!/usr/bin/env python3
"""Extract published growth curves; never calculate a patient's percentile."""
import argparse
import csv
from decimal import Decimal, ROUND_HALF_UP
import hashlib
import io
from pathlib import Path
import urllib.request
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[2]
SOURCES = {
    'cdc-weight.csv': 'https://www.cdc.gov/growthcharts/data/zscore/wtage.csv',
    'cdc-height.csv': 'https://www.cdc.gov/growthcharts/data/zscore/statage.csv',
    'who-weight-girls.xlsx': 'https://cdn.who.int/media/docs/default-source/child-growth/child-growth-standards/indicators/weight-for-age/tab_wfa_girls_p_0_5.xlsx',
    'who-weight-boys.xlsx': 'https://cdn.who.int/media/docs/default-source/child-growth/child-growth-standards/indicators/weight-for-age/tab_wfa_boys_p_0_5.xlsx',
    'who-height-girls.xlsx': 'https://cdn.who.int/media/docs/default-source/child-growth/child-growth-standards/indicators/length-height-for-age/tab_lhfa_girls_p_0_2.xlsx',
    'who-height-boys.xlsx': 'https://cdn.who.int/media/docs/default-source/child-growth/child-growth-standards/indicators/length-height-for-age/tab_lhfa_boys_p_0_2.xlsx',
}
NS = {'s': 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}


def workbook_rows(data):
    """Read numeric table cells, preserving header identities and source precision."""
    with zipfile.ZipFile(io.BytesIO(data)) as book:
        strings = [''.join(cell.itertext()) for cell in ET.fromstring(
            book.read('xl/sharedStrings.xml')).findall('s:si', NS)]
        rows = []
        for row in ET.fromstring(book.read('xl/worksheets/sheet1.xml')).findall('.//s:row', NS):
            values = {}
            for cell in row.findall('s:c', NS):
                assert cell.find('s:f', NS) is None, 'Expected published values, not formulas'
                value = cell.findtext('s:v', default='', namespaces=NS)
                if cell.get('t') == 's':
                    value = strings[int(value)]
                column = ''.join(c for c in cell.get('r') if c.isalpha())
                values[column] = value
            rows.append(values)
        headers = rows[0]
        return [{headers[column]: value for column, value in row.items() if column in headers}
                for row in rows[1:]]


def scaled(value, scale):
    return int((Decimal(value) * scale).quantize(Decimal(1), rounding=ROUND_HALF_UP))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source-dir', default='/tmp/amb-research/growth')
    parser.add_argument('--out', default=str(ROOT / 'lean/Ehr/Render/GrowthStandards.lean'))
    args = parser.parse_args()
    cache = Path(args.source_dir)
    cache.mkdir(parents=True, exist_ok=True)
    curves = []
    evidence = []
    for name, url in SOURCES.items():
        path = cache / name
        if not path.exists():
            request = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
            path.write_bytes(urllib.request.urlopen(request, timeout=30).read())
        raw = path.read_bytes()
        evidence.append((name, url, hashlib.sha256(raw).hexdigest()))
        rows = list(csv.DictReader(io.StringIO(raw.decode('utf-8-sig')))) if name.endswith('.csv') else workbook_rows(raw)
        measure, unit = ('Weight', 'kg') if 'weight' in name else ('Height', 'cm')
        source = 'CDC 2000' if name.startswith('cdc') else 'WHO 2006'
        for sex, population in [('M', 'Boys'), ('F', 'Girls')]:
            if name.startswith('who') and (('boys' in name) != (sex == 'M')):
                continue
            selected = [row for row in rows if not name.startswith('cdc') or row['Sex'] == ('1' if sex == 'M' else '2')]
            for percentile in [5, 50, 95]:
                points = [(scaled(row.get('Agemos', row.get('Month')), 10), scaled(row[f'P{percentile}'], 100))
                          for row in selected if name.startswith('cdc') or Decimal(row['Month']) <= 24]
                assert points and all(a[0] < b[0] for a, b in zip(points, points[1:])), (name, sex)
                assert (points[0][0], points[-1][0]) == ((240, 2400) if source == 'CDC 2000' else (0, 240))
                curves.append((sex, measure, unit, f'{percentile}th', source, population, points))
    lines = ['import Ehr.Render.UiData', '', '/-! Published reference curves, not patient percentile estimates.',
             'Generated by scripts/realism/generate-growth-reference.py.',
             'WHO values retain the published tenth-unit precision; CDC values are rounded',
             'to hundredths for drawing. Curves stop at the source age boundaries.', '', 'Source SHA-256 and URLs:']
    for name, url, digest in evidence:
        lines.extend([f'{name}: {digest}', url])
    lines.extend(['-/', '', 'namespace Ehr.Render', ''])
    names = []
    for sex, measure, unit, percentile, source, population, points in curves:
        name = source.split()[0].lower() + measure + population + percentile.replace('th', '')
        names.append((sex, name))
        text = ', '.join(f'({age}, {value})' for age, value in points)
        lines.extend([f'/-- Published {source} {percentile} {measure.lower()}-for-age samples, {population.lower()}. -/',
                      f'def {name} : UiChartReference where',
                      f'  measure := "{measure}"', f'  unit := "{unit}"', f'  percentile := "{percentile}"',
                      f'  source := "{source} {"weight-for-age" if measure == "Weight" else "length-for-age" if source == "WHO 2006" else "stature-for-age"} ({"0–24" if source == "WHO 2006" else "24–240"} mo)"',
                      f'  population := "{population}"', f'  points := [{text}]', ''])
    lines.extend(['/-- Published 5th, 50th and 95th reference samples by recorded birth sex. -/',
                  'def growthReferenceCatalog : List (String × UiChartReference) :=',
                  '  ['])
    lines.extend('    ("' + sex + '", ' + name + ')' + (',' if i + 1 < len(names) else '')
                 for i, (sex, name) in enumerate(names))
    lines.extend(['  ]', '', '/-- Select only a documented reference population and supplied measures.',
                  'The six-month margin is plot context; it never extrapolates a curve. -/',
                  'def uiGrowthReferences (d : Display) : List UiChartReference :=',
                  '  match d.growthReferenceSex? with',
                  '  | none => []',
                  '  | some sex =>',
                  '    let recorded := d.growth.filter fun p => isoDateValid d.banner.dob &&',
                  '      isoDateValid p.date && d.banner.dob ≤ p.date',
                  '    if recorded.isEmpty then [] else',
                  '    let firstAge := (recorded.head?).map (·.ageMonths) |>.getD 0',
                  '    let lo := (recorded.foldl (fun age p => min age p.ageMonths) firstAge) - 6',
                  '    let hi := min 240 ((recorded.foldl (fun age p => max age p.ageMonths) 0) + 6)',
                  '    growthReferenceCatalog.filterMap fun (population, reference) =>',
                  '      let measured := if reference.measure == "Weight" then recorded.any (·.weightTenths?.isSome)',
                  '        else recorded.any (·.heightTenths?.isSome)',
                  '      if population != sex || !measured then none else',
                  '      let points := reference.points.filter fun (age, _) => lo * 10 ≤ age && age ≤ hi * 10',
                  '      if points.length < 2 then none else some { reference with points }', '',
                  '/-- The published WHO newborn median for boys is 3.3 kg. -/',
                  'def newbornWeightReferenceExample : Option (Nat × Nat) :=',
                  '  ((growthReferenceCatalog.find? fun (sex, r) => sex == "M" && r.measure == "Weight" &&',
                  '    r.source.startsWith "WHO 2006" && r.percentile == "50th").bind fun (_, r) => r.points.head?)',
                  '#guard newbornWeightReferenceExample == some (0, 330)', '',
                  '/-- An unrecorded reference population never acquires a curve. -/',
                  'def missingGrowthReferenceExample : List UiChartReference := uiGrowthReferences Display.empty',
                  '#guard missingGrowthReferenceExample.isEmpty', '', 'end Ehr.Render', ''])
    Path(args.out).write_text('\n'.join(lines))
    print(f'{len(curves)} published curves, {sum(len(c[-1]) for c in curves)} samples; no patient percentile calculation')


if __name__ == '__main__':
    main()
