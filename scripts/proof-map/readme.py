"""Write (or check) the generated proof-map section of README.md.

usage: readme.py <data.json> <README.md> [--check]
The section sits between the PROOF-MAP markers. With --check, exit 1 if it is
out of date instead of rewriting it. Output is Mermaid charts with no line
numbers or commit hashes, so it only changes when the proof structure changes."""
import collections, html, json, sys

BEGIN = '<!-- PROOF-MAP:BEGIN (generated by scripts/proof-map/build.sh --readme; do not edit) -->'
END = '<!-- PROOF-MAP:END -->'

data = json.load(open(sys.argv[1]))
readme_path, check = sys.argv[2], '--check' in sys.argv[3:]
D, layers = data['decls'], data['layers']
mods = [m[0] for m in data['modules']]


def layer_for(mod):
    best = None
    for L in layers:
        for p in L['p']:
            if (mod == p or mod.startswith(p + '.')) and (best is None or len(p) > best[1]):
                best = (L, len(p))
    return best[0] if best else layers[-1]


lay = [layer_for(mods[r[2]]) for r in D]
esc = html.escape


def short(i):
    """Name without the shared namespace prefix of its module, for readability."""
    n = D[i][0]
    for pre in ('Ehr.Commit.Protocol.', 'Ehr.', 'CommitProtocol.'):
        if n.startswith(pre): return n[len(pre):]
    return n


lemmas = lambda i: sorted({j for j in D[i][7] if D[j][1] == 't' and j != i}, key=lambda j: D[j][0])


def label(i):
    return esc(short(i)).replace('&quot;', '#quot;').replace('&#x27;', "'")


STYLE = ['  classDef spec fill:#fdf3dc,stroke:#b7791f,color:#3d2a06',
         '  classDef guar fill:#e3eefc,stroke:#2b6cb0,color:#0f2747',
         '  classDef head fill:#e3eefc,stroke:#2b6cb0,stroke-width:2px,color:#0f2747,font-weight:bold',
         '  classDef lemma fill:#ffffff,stroke:#8a94a6,color:#1f2937',
         '  classDef other fill:#f4f4f5,stroke:#a1a1aa,stroke-dasharray:4 3,color:#3f3f46']


def overview():
    """Specification and guarantee layers; an arrow means statements in the
    first are phrased in terms of definitions in the second. Every such pair is
    drawn: thick for 100+ references, dotted for fewer than 5."""
    shown = [L for L in layers if L['cls'] in ('spec', 'guar')]
    ids = {L['id'] for L in shown}
    edges = collections.Counter()
    for i, r in enumerate(D):
        for j in r[6]:
            a, b = lay[i]['id'], lay[j]['id']
            if a != b and a in ids and b in ids: edges[(a, b)] += 1
    arrow = lambda n: '==>' if n >= 100 else ('-.->' if n < 5 else '-->')
    kept = [f'  {a} {arrow(n)} {b}' for (a, b), n in sorted(edges.items())]
    out = ['```mermaid', 'flowchart TB']
    for c, title in (('guar', 'Guarantees'), ('spec', 'Specification')):
        out.append(f'  subgraph {c}_g["{title}"]')
        for L in shown:
            if L['cls'] == c:
                n = sum(1 for x, r in zip(lay, D) if x is L and r[1] == 't')
                h = sum(1 for x, r in zip(lay, D) if x is L and r[8])
                out.append(f'    {L["id"]}["{esc(L["name"])}<br/>{n} theorems, {h} headline"]:::{c}')
        out.append('  end')
    out += kept + STYLE[:2] + ['```']
    return out


def chart(L, hs):
    """Headline claims of one layer and the lemmas their proofs cite, with the
    citations among them. Lemmas from other layers are dashed."""
    nodes = set(hs)
    for i in hs: nodes |= set(lemmas(i))
    order = sorted(nodes, key=lambda i: (0 if i in hs else 1, D[i][0]))
    nid = {i: f'n{k}' for k, i in enumerate(order)}
    out = ['```mermaid', 'flowchart LR']
    for i in order:
        c = 'head' if i in hs else ('lemma' if lay[i] is L else 'other')
        out.append(f'  {nid[i]}["{label(i)}"]:::{c}')
    for i in order:
        for j in lemmas(i):
            if j in nodes: out.append(f'  {nid[i]} --> {nid[j]}')
    return out + STYLE[2:] + ['```']


def section():
    lines = [BEGIN, '',
             'Generated from the compiled Lean environment. In the overview an arrow reads',
             '"is stated in terms of" (thick: 100+ references, dotted: under 5). In each',
             'layer\'s chart below an arrow reads "its proof cites": headline claims are',
             'bold, lemmas they cite directly are white, lemmas from other layers are',
             'dashed. The interactive version, with search, full',
             'trees and each claim\'s trust surface, is the `proof-map` artifact of every CI',
             'run.', '']
    lines += overview() + ['']
    heads = collections.defaultdict(list)
    for i, r in enumerate(D):
        if r[8]: heads[lay[i]['id']].append(i)
    for L in layers:
        hs = sorted(heads.get(L['id'], []), key=lambda i: D[i][0])
        if not hs: continue
        lines += [f'<details><summary><b>{esc(L["name"])}</b>: {len(hs)} headline '
                  f'claim{"s" if len(hs) != 1 else ""}. {esc(L["note"])}</summary>', '']
        lines += chart(L, hs)
        lines += ['', '</details>', '']
    lines.append(END)
    return '\n'.join(lines)


text = open(readme_path).read()
if text.count(BEGIN) != 1 or text.count(END) != 1:
    sys.exit(f'{readme_path}: expected exactly one PROOF-MAP:BEGIN/END marker pair')
a, b = text.index(BEGIN), text.index(END) + len(END)
new = text[:a] + section() + text[b:]
if check:
    if new != text:
        sys.exit('README proof-map section is out of date; run scripts/proof-map/build.sh --readme')
    print('README proof-map section is current')
elif new != text:
    open(readme_path, 'w').write(new)
    print('README proof-map section updated')
else:
    print('README proof-map section already current')
